"""ML-Agents 1.1.0 entry point with exact mastery-based lesson advancement.

uv run python Assets/Scripts/AI/Training/train_phase2.py <yaml> --run-id=Phase2M4 --force
No installed ML-Agents files are edited. The manager adapter lives in this process only.
"""
import copy
from datetime import datetime
from pathlib import Path
import socket

from phase2_mastery import MasteryWindow, StairPracticeWindow, NearSearchWindow, MixedSearchWindow


def restore_window(saved, stage, coverage):
    previous = saved.get("phase2_mastery")
    if (coverage and stage == 4 and previous
            and previous.get("revision") == MasteryWindow.REVISION and previous.get("stage") == 3):
        return MasteryWindow(4)  # First approved search -> coverage handoff, not old search outcomes.
    return MasteryWindow.restore(previous, stage)


def main():
    import mlagents.trainers
    from mlagents.trainers import learn
    from mlagents.trainers.environment_parameter_manager import EnvironmentParameterManager
    from mlagents.trainers.stats import StatsReporter, StatsWriter, StatsSummary
    from mlagents.trainers.training_status import GlobalTrainingStatus, StatusType
    from mlagents_envs.logging_util import get_logger
    from mlagents_envs.side_channel.stats_side_channel import StatsAggregationMethod

    if mlagents.trainers.__version__ != "1.1.0":
        raise RuntimeError("This mastery adapter is tested with mlagents==1.1.0 only.")
    options = learn.parse_command_line()
    parameters = options.environment_parameters
    practice_enabled = ("stair_practice" in parameters
                        and parameters["stair_practice"].curriculum[0].value.value >= 0.5)
    near_enabled = ("near_search_curriculum" in parameters
                    and parameters["near_search_curriculum"].curriculum[0].value.value >= 0.5)
    mixed_enabled = ("mixed_search_curriculum" in parameters
                     and parameters["mixed_search_curriculum"].curriculum[0].value.value >= 0.5)
    coverage = "stair_search_lesson" not in parameters
    key = "floor_lesson" if coverage else "stair_search_lesson"
    values = [4, 5] if coverage else [0, 1, 2, 3]
    lessons = parameters.get(key)
    if (lessons is None or [x.value.value for x in lessons.curriculum] != values
            or "mastery_protocol" not in parameters):
        raise ValueError("Use the updated search/resume YAML or a coverage YAML generated by the evaluation gate.")
    if coverage and parameters["stair_eval_gate_passed"].curriculum[0].value.value != 1:
        raise ValueError("Coverage requires the fixed-seed stair evaluation gate to pass first.")
    if options.env_settings.num_envs != 1 or options.env_settings.num_areas != 1:
        raise ValueError("Mastery outcome protocol currently supports one environment/area only.")
    settings = options.checkpoint_settings
    if coverage and not settings.resume:
        raise ValueError("Approved coverage must continue the same run with --resume, never --force.")
    if settings.resume and settings.force:
        raise ValueError("Choose either --resume or --force, not both.")
    if not settings.resume:
        initial = options.behaviors["Explorer"].init_path
        if not initial or not Path(initial).is_file():
            raise ValueError("A new run requires an existing pinned initialization checkpoint from its YAML.")
    run_dir = Path(settings.write_path).resolve()
    root = Path(__file__).resolve().parents[4]
    results = (root / "results").resolve()
    if run_dir.parent != results or run_dir.name != settings.run_id:
        raise ValueError("For safe backups, use a simple run-id inside this project's results folder.")
    status_file = run_dir / "run_logs/training_status.json"
    if settings.resume:
        import json
        saved = json.loads(status_file.read_text(encoding="utf-8-sig"))
        stage = values[saved.get(key, {}).get("lesson_num", 0)]
        restore_window(saved, stage, coverage)
        if mixed_enabled and "phase2_mixed_search" not in saved:
            raise ValueError("Do not resume the old run with the mixed-search config. Start a separate run from its pinned weights.")
    if settings.force and run_dir.exists():
        # Refuse to move live run data while an Editor trainer owns port 5004.
        port = 5004 if options.env_settings.env_path is None else options.env_settings.base_port
        with socket.socket() as probe:
            if hasattr(socket, "SO_EXCLUSIVEADDRUSE"):
                probe.setsockopt(socket.SOL_SOCKET, socket.SO_EXCLUSIVEADDRUSE, 1)
            try:
                probe.bind(("localhost", port))
            except OSError as exc:
                raise RuntimeError("Stop the existing trainer with Ctrl+C and stop Unity Play Mode before restarting.") from exc
        archive = results / "restart_backups"
        target = archive / (settings.run_id + "_" + datetime.now().strftime("%Y%m%d_%H%M%S_%f"))
        if target.resolve().parent != archive.resolve():
            raise ValueError("Invalid backup path")
        archive.mkdir(exist_ok=True)
        run_dir.rename(target)
        print(f"Previous results backed up to: {target}", flush=True)
    parameters["mastery_driver"] = copy.deepcopy(parameters["mastery_protocol"])
    if near_enabled:
        parameters["near_search_driver"] = copy.deepcopy(parameters["near_search_curriculum"])
    if mixed_enabled:
        parameters["mixed_search_driver"] = copy.deepcopy(parameters["mixed_search_curriculum"])
    logger = get_logger("phase2_mastery")
    bank = MasteryWindow()
    practice = StairPracticeWindow()
    near = NearSearchWindow()
    mixed = MixedSearchWindow()

    def persist():
        GlobalTrainingStatus.saved_state["phase2_mastery"] = bank.state()
        if practice_enabled:
            GlobalTrainingStatus.saved_state["phase2_stair_practice"] = practice.state()
        if near_enabled:
            GlobalTrainingStatus.saved_state["phase2_near_search"] = near.state()
        if mixed_enabled:
            GlobalTrainingStatus.saved_state["phase2_mixed_search"] = mixed.state()

    class MasteryWriter(StatsWriter):
        def on_add_stat(self, category, key, value, aggregation=StatsAggregationMethod.AVERAGE):
            if category == "Explorer" and key == "AI/Mastery Outcome":
                bank.add(value)
                persist()
            elif (category == "Explorer" and key == "AI/Stair Practice Outcome"
                  and practice_enabled and bank.stage == 1):
                practice.add(value)
                persist()
            elif (category == "Explorer" and key == "AI/Near Search Outcome"
                  and near_enabled and bank.stage == 2):
                near.add(value)
                persist()
            elif (category == "Explorer" and key == "AI/Mixed Search Outcome"
                  and mixed_enabled and bank.stage == 3):
                mixed.add(value)
                persist()

        def write_stats(self, category, values, step):
            if category != "Explorer":
                return
            summary = bank.summary()
            for key, value in summary.items():
                values["AI/Mastery/" + key] = StatsSummary([float(value)], StatsAggregationMethod.AVERAGE)
            values["AI/Mastery/lesson"] = StatsSummary([float(bank.stage)], StatsAggregationMethod.AVERAGE)
            if mixed_enabled and bank.stage == 3:
                m = mixed.summary()
                for label, value in {"level": mixed.stage, **m,
                                     "mastered": mixed.stage == MixedSearchWindow.LAST_LEVEL and mixed.ready()}.items():
                    values["AI/MixedSearch/" + label] = StatsSummary([float(value)], StatsAggregationMethod.AVERAGE)
                logger.info(f"Mixed search {mixed.stage}: {m['episodes']}/100; up {m['up_success']:.0%}, "
                            f"down {m['down_success']:.0%}; near {m['near_success']:.0%} (n={m['near_trials']}), "
                            f"far {m['far_success']:.0%} (n={m['far_trials']}).")
            if near_enabled and bank.stage == 2:
                n = near.summary()
                for label, value in {"level": near.stage, **n}.items():
                    values["AI/NearSearch/" + label] = StatsSummary([float(value)], StatsAggregationMethod.AVERAGE)
                logger.info(f"Near search {near.stage}: {n['episodes']}/100; up {n['up_success']:.0%} "
                            f"(n={n['up_trials']}), down {n['down_success']:.0%} (n={n['down_trials']}).")
            if practice_enabled and bank.stage == 1:
                p = practice.summary()
                values["AI/Practice/level"] = StatsSummary([float(practice.stage)], StatsAggregationMethod.AVERAGE)
                values["AI/Practice/episodes"] = StatsSummary([float(p["episodes"])], StatsAggregationMethod.AVERAGE)
                values["AI/Practice/up_success"] = StatsSummary([float(p["up_success"])], StatsAggregationMethod.AVERAGE)
                logger.info(f"Stair practice {practice.stage}: {p['episodes']}/100; ascent success {p['up_success']:.0%}.")
            logger.info(f"Mastery lesson {bank.stage}: {summary['episodes']}/100 episodes; "
                        f"success {summary['success']:.0%}; up {summary['up_success']:.0%} "
                        f"(n={summary['up_trials']}), down {summary['down_success']:.0%} "
                        f"(n={summary['down_trials']}).")

    class MasteryManager(EnvironmentParameterManager):
        def __init__(self, settings=None, run_seed=-1, restore=False):
            nonlocal bank, practice, near, mixed
            super().__init__(settings, run_seed, restore)
            if mixed_enabled and not coverage and not restore:
                # New experimental branch inherits model weights, not old
                # curriculum windows. Other runs still start exactly as before.
                GlobalTrainingStatus.set_parameter_state(key, StatusType.LESSON_NUM, 3)
            stage = values[GlobalTrainingStatus.get_parameter_state(key, StatusType.LESSON_NUM)]
            bank = (restore_window(GlobalTrainingStatus.saved_state, stage, coverage)
                    if restore else MasteryWindow(stage))
            if practice_enabled:
                saved_practice = GlobalTrainingStatus.saved_state.get("phase2_stair_practice") if restore else None
                practice = (StairPracticeWindow.restore(saved_practice, saved_practice["stage"])
                            if saved_practice else StairPracticeWindow(0 if stage <= 1 else 2))
                if restore and saved_practice is None and stage == 1:
                    # Keep model/optimizer/step; old unassisted failures are not
                    # evidence for the newly introduced guided practice level.
                    bank = MasteryWindow(1)
                    logger.info("Added stair practice to the current checkpoint: reset lesson-1 outcome window only; weights/step preserved.")
            if near_enabled:
                saved_near = GlobalTrainingStatus.saved_state.get("phase2_near_search") if restore else None
                near = (NearSearchWindow.restore(saved_near, saved_near["stage"])
                        if saved_near else NearSearchWindow(0 if stage <= 2 else 3))
                if restore and saved_near is None and stage == 2:
                    bank = MasteryWindow(2)
                    logger.info("Added gradual near-search: start local level 0; clear old lesson-2 outcomes only. Model/optimizer/step and main lesson 2 preserved.")
            if mixed_enabled:
                saved_mixed = GlobalTrainingStatus.saved_state.get("phase2_mixed_search") if restore else None
                mixed = (MixedSearchWindow.restore(saved_mixed, saved_mixed["stage"])
                         if restore else MixedSearchWindow())
            persist()

        def get_current_samplers(self):
            from mlagents.trainers.settings import ConstantSettings
            samplers = super().get_current_samplers()
            if practice_enabled:
                samplers["stair_practice_level"] = ConstantSettings(value=practice.stage)
            if near_enabled:
                samplers["near_search_level"] = ConstantSettings(value=near.stage)
            if mixed_enabled:
                samplers["mixed_search_level"] = ConstantSettings(value=mixed.stage)
            return samplers

        def update_lessons(self, trainer_steps, trainer_max_steps, trainer_reward_buffer):
            nonlocal bank, practice, near, mixed
            # No reward/step proxy is consulted here. Native machinery still
            # owns parameter delivery and checkpoint lesson state.
            with StatsReporter.lock:
                if mixed_enabled and bank.stage == 3:
                    if mixed.ready() and mixed.stage < MixedSearchWindow.LAST_LEVEL:
                        logger.info(f"Mixed search passed: {mixed.stage} -> {mixed.stage + 1}: {mixed.summary()}")
                        mixed = MixedSearchWindow(mixed.stage + 1)
                        bank = MasteryWindow(3)
                        persist()
                        return True, True
                    # Final mastery still requires the independent fixed-seed
                    # evaluation gate; never jump directly to coverage here.
                    return False, False
                if practice_enabled and bank.stage == 1:
                    if not practice.ready():
                        return False, False
                    if practice.stage < 2:
                        logger.info(f"Stair practice passed: {practice.stage} -> {practice.stage + 1}: {practice.summary()}")
                        practice = StairPracticeWindow(practice.stage + 1)
                        bank = MasteryWindow(1)
                        GlobalTrainingStatus.saved_state.update({
                            "phase2_mastery": bank.state(), "phase2_stair_practice": practice.state()})
                        return True, True
                if near_enabled and bank.stage == 2:
                    if not near.ready():
                        return False, False
                    if near.stage < 3:
                        logger.info(f"Near search passed: {near.stage} -> {near.stage + 1}: {near.summary()}")
                        near = NearSearchWindow(near.stage + 1)
                        bank = MasteryWindow(2)
                        GlobalTrainingStatus.saved_state.update({
                            "phase2_mastery": bank.state(), "phase2_near_search": near.state()})
                        return True, True
                if not bank.ready():
                    return False, False
                stage = bank.stage + 1
                logger.info(f"Mastery passed: advancing {bank.stage} -> {stage}: {bank.summary()}")
                bank = MasteryWindow(stage)
                # Publish lesson and window together so a background checkpoint
                # cannot observe a new lesson paired with the old sample window.
                GlobalTrainingStatus.saved_state.update({
                    key: {**GlobalTrainingStatus.saved_state[key], "lesson_num": values.index(stage)},
                    "phase2_mastery": bank.state(),
                })
            self.log_current_lesson(key)
            return True, True

    StatsReporter.add_writer(MasteryWriter())
    learn.EnvironmentParameterManager = MasteryManager
    learn.run_cli(options)


if __name__ == "__main__":
    main()
